export const UNIT_PRICE = 1200;

/** خصم لكل قطعة حسب الكمية */
export function unitDiscount(qty: number): number {
  const map: Record<number, number> = { 1: 0, 2: 100, 3: 150, 4: 200, 5: 250 };
  return map[qty] ?? 250;
}

export function totalFor(qty: number): number {
  return (UNIT_PRICE - unitDiscount(qty)) * qty;
}
